//go:build ignore

// Command gen_envd_internal_routes derives the set of envd request paths
// reserved for the orchestrator from the envd OpenAPI spec, and writes them to
// envd_internal_routes.gen.go for the ingress policy to reject.
//
// The spec is the single source of truth: an operation marked `x-internal: true`
// lands in the generated set, and nothing else does. That keeps the proxy's
// rejection list from drifting away from the spec as envd's control plane grows.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"slices"
	"strconv"
	"strings"

	"github.com/getkin/kin-openapi/openapi3"
)

const (
	specPath   = "../../../envd/spec/envd.yaml"
	outputPath = "envd_internal_routes.gen.go"

	// internalExtension marks an operation as belonging to the orchestrator's
	// control plane rather than to the sandbox's public surface.
	internalExtension = "x-internal"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "gen_envd_internal_routes: %v\n", err)
		os.Exit(1)
	}
}

func run() error {
	paths, err := internalPaths(specPath)
	if err != nil {
		return err
	}

	if len(paths) == 0 {
		return fmt.Errorf("no operation in %s is marked %s; refusing to generate an empty set", specPath, internalExtension)
	}

	source, err := render(paths)
	if err != nil {
		return err
	}

	return os.WriteFile(outputPath, source, 0o644)
}

// internalPaths returns the sorted spec paths whose operations are marked
// internal.
//
// The proxy rejects an internal path for every method, so a path that mixes
// internal and public operations cannot be expressed and is an error rather
// than a silent choice between over- and under-blocking.
func internalPaths(spec string) ([]string, error) {
	loader := openapi3.NewLoader()

	doc, err := loader.LoadFromFile(spec)
	if err != nil {
		return nil, fmt.Errorf("load %s: %w", spec, err)
	}

	var paths []string

	for path, item := range doc.Paths.Map() {
		var internal, public []string

		for method, op := range item.Operations() {
			if isInternal(op) {
				internal = append(internal, method)
			} else {
				public = append(public, method)
			}
		}

		if len(internal) == 0 {
			continue
		}

		if len(public) > 0 {
			slices.Sort(public)

			return nil, fmt.Errorf(
				"path %s mixes internal and public operations (public: %v); the proxy rejects a path for every method, so mark every operation on %s internal or none of them",
				path, public, path,
			)
		}

		// The proxy matches a path by exact string, so a path template would
		// generate a rule no request can ever equal — every check here and in the
		// proxy's tests would still pass while the route stayed reachable. Fail
		// the build instead, until the matcher can express a template.
		if strings.ContainsAny(path, "{}") {
			return nil, fmt.Errorf(
				"internal path %s is templated; the proxy matches paths exactly, so this would generate a rule that never matches and leave %s reachable. Teach isInternalEnvdPath to match templates before marking one internal",
				path, path,
			)
		}

		paths = append(paths, path)
	}

	slices.Sort(paths)

	return paths, nil
}

// isInternal reports whether the operation carries `x-internal: true`. Any other
// value for the extension is a typo worth surfacing rather than treating as
// "not internal", but a generator cannot fail on it without also rejecting
// operations that legitimately set it to false, so only true counts.
func isInternal(op *openapi3.Operation) bool {
	value, ok := op.Extensions[internalExtension]
	if !ok {
		return false
	}

	internal, ok := value.(bool)

	return ok && internal
}

func render(paths []string) ([]byte, error) {
	var buf bytes.Buffer

	fmt.Fprintf(&buf, "// Code generated by gen_envd_internal_routes.go from %s; DO NOT EDIT.\n\n", specPath)
	buf.WriteString("package proxy\n\n")
	buf.WriteString("// specInternalPaths are the envd request paths whose operations the envd\n")
	buf.WriteString("// OpenAPI spec marks `x-internal: true`: the orchestrator's control plane,\n")
	buf.WriteString("// which no request arriving through the public sandbox URL may reach.\n")
	buf.WriteString("var specInternalPaths = []string{\n")

	for _, path := range paths {
		fmt.Fprintf(&buf, "\t%s,\n", strconv.Quote(path))
	}

	buf.WriteString("}\n")

	source, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w", err)
	}

	return source, nil
}

CREATE TABLE public.envs (
    id text PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL,
    public boolean NOT NULL DEFAULT false,
    build_count integer NOT NULL DEFAULT 1,
    spawn_count bigint NOT NULL DEFAULT '0'::bigint,
    last_spawned_at timestamptz,
    team_id uuid NOT NULL CONSTRAINT envs_teams_envs REFERENCES public.teams (id),
    created_by uuid CONSTRAINT envs_users_created_envs REFERENCES public.users (id) ON DELETE SET NULL,
    cluster_id uuid,
    source text NOT NULL DEFAULT 'template',
    deleted_at timestamptz
) WITH (autovacuum_vacuum_scale_factor = 0.02, autovacuum_analyze_scale_factor = 0.01);

CREATE INDEX envs_cluster_id ON public.envs (cluster_id) WHERE cluster_id IS NOT NULL;
CREATE INDEX idx_envs_active_id ON public.envs (id) WHERE deleted_at IS NULL;
CREATE INDEX idx_envs_team_id_source ON public.envs (team_id, source);
CREATE INDEX idx_envs_team_source_created_at ON public.envs (team_id, source, created_at DESC, id DESC);
CREATE INDEX idx_envs_team_updated_at_templates ON public.envs (team_id, updated_at DESC, id DESC) WHERE source = 'template';

COMMENT ON COLUMN public.envs.spawn_count IS 'Number of times the env was spawned';
COMMENT ON COLUMN public.envs.last_spawned_at IS 'Timestamp of the last time the env was spawned';

CREATE VIEW public.active_envs AS
SELECT id, created_at, updated_at, public, build_count, spawn_count, last_spawned_at, team_id, created_by, cluster_id, source
FROM public.envs
WHERE deleted_at IS NULL;


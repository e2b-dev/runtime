-- The public and projection schemas that ../migrations builds. Migrations are
-- generated from edits to this file. Column statistics targets and comments
-- are not compared, so changing one needs a hand-written migration. Table
-- storage parameters (WITH options) are compared but not generated:
-- generation fails and prints the ALTER TABLE to write. Rows the migrations
-- insert, such as the public.default_limits row, are not declared.

CREATE EXTENSION unaccent WITH SCHEMA public;

CREATE EXTENSION btree_gin WITH SCHEMA public;

CREATE SCHEMA projection;

-- Fills the legacy status from status_group, so writers can stop naming status
-- before the column is dropped.
CREATE FUNCTION public.compute_status_group() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
  IF (TG_OP = 'INSERT' AND NEW.status_group IS NULL)
     OR (TG_OP = 'UPDATE' AND NEW.status IS DISTINCT FROM OLD.status) THEN
    NEW.status_group := CASE
      WHEN NEW.status IN ('pending', 'waiting') THEN 'pending'
      WHEN NEW.status IN ('in_progress', 'building', 'snapshotting') THEN 'in_progress'
      WHEN NEW.status IN ('ready', 'uploaded', 'success') THEN 'ready'
      ELSE 'failed'
    END;
  ELSE
    NEW.status := CASE NEW.status_group
      WHEN 'pending' THEN 'waiting'
      WHEN 'in_progress' THEN 'building'
      WHEN 'ready' THEN 'uploaded'
      WHEN 'failed' THEN 'failed'
    END;
  END IF;
  RETURN NEW;
END;
$$;

CREATE FUNCTION public.default_limits_keep_row() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    RAISE EXCEPTION 'public.default_limits must keep its row; update it instead';
END
$$;

CREATE FUNCTION public.fix_snapshots_metadata_json_null() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
  IF NEW.metadata IS NULL OR NEW.metadata = 'null'::jsonb THEN
    NEW.metadata := '{}'::jsonb;
  END IF;
  RETURN NEW;
END;
$$;

CREATE FUNCTION public.try_cast_uuid(p_value text) RETURNS uuid
    LANGUAGE plpgsql IMMUTABLE
    AS $$
BEGIN
    RETURN p_value::uuid;
EXCEPTION WHEN invalid_text_representation THEN
    RETURN NULL;
END;
$$;

